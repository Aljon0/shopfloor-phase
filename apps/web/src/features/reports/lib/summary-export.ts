import { toCsv, type CsvCell } from '@/lib/csv'
import type { OperationalSummary } from './summary'

const round1 = (v: number | null): CsvCell => (v === null ? null : Math.round(v * 10) / 10)

/**
 * One CSV file with labelled sections (details, totals, lines, days, downtime). Sections are
 * separated by a blank line so the file still opens cleanly in a spreadsheet.
 */
export function buildSummaryCsv(s: OperationalSummary): { filename: string; csv: string } {
  const k = s.kpis
  const sections = [
    toCsv(['Report', 'Value'], [
      ['Title', s.title],
      ['Type', s.kind === 'daily' ? 'Daily' : 'Weekly'],
      ['Period from', s.range.from],
      ['Period to', s.range.to],
      ['Period status', s.inProgress ? 'In progress (not complete)' : 'Complete'],
      ['Generated by', s.meta.generatedBy],
      ['Generated at', s.meta.generatedAt],
      ['Basis', 'Approved reports only; times in factory local time'],
      ['Approved reports counted', s.approvedReportCount],
      ['Awaiting review (not counted)', s.excluded.awaitingReview],
      ['Returned for correction (not counted)', s.excluded.returned],
      ['Draft (not counted)', s.excluded.draft],
    ]),
    toCsv(['Totals', 'Value'], [
      ['Produced quantity', k.producedQuantity],
      ['Good quantity', k.goodQuantity],
      ['Rejected quantity', k.rejectedQuantity],
      ['Planned quantity', k.plannedQuantity],
      ['Rejection rate (%)', round1(k.rejectionRate)],
      ['Target achievement (%)', round1(k.targetAchievement)],
      ['Downtime (min)', k.downtimeMinutes],
      ['Downtime events', k.downtimeEvents],
    ]),
    toCsv(
      ['Production line', 'Produced quantity', 'Rejected quantity', 'Good quantity', 'Planned quantity', 'Rejection rate (%)', 'Target achievement (%)', 'Downtime (min)'],
      s.lines.map((l) => [l.lineName, l.producedQuantity, l.rejectedQuantity, l.goodQuantity, l.plannedQuantity, round1(l.rejectionRate), round1(l.targetAchievement), l.downtimeMinutes]),
    ),
    toCsv(
      ['Date', 'Produced quantity', 'Rejected quantity', 'Good quantity', 'Planned quantity', 'Rejection rate (%)', 'Target achievement (%)', 'Downtime (min)'],
      s.daily.map((d) => [d.date, d.producedQuantity, d.rejectedQuantity, d.goodQuantity, d.plannedQuantity, round1(d.rejectionRate), round1(d.targetAchievement), d.downtimeMinutes]),
    ),
    toCsv(
      ['Downtime category', 'Events', 'Downtime (min)'],
      s.downtimeByCategory.map((c) => [c.label, c.events, c.minutes]),
    ),
  ]
  const stem = s.kind === 'daily' ? `shopfloor-daily-summary-${s.range.from}` : `shopfloor-weekly-summary-${s.range.from}_to_${s.range.to}`
  return { filename: `${stem}.csv`, csv: sections.join('\r\n\r\n') }
}
