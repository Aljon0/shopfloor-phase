import { describe, expect, it } from 'vitest'
import { buildDashboard } from '@/features/dashboard/lib/aggregate'
import { ACTIVITY, DOWNTIME_EVENTS, LINES, ORDERS, PRODUCTS, REPORTS } from '@/mocks/seed'
import { buildSummary, periodFor, shiftAnchor, weekStart } from './summary'
import { buildSummaryCsv } from './summary-export'

const input = { lines: LINES, products: PRODUCTS, orders: ORDERS, reports: REPORTS, downtimeEvents: DOWNTIME_EVENTS, activity: ACTIVITY }
const meta = { generatedBy: 'Mira Santos', generatedAt: '2026-11-08T01:00:00.000Z', today: '2026-11-07' }

describe('report periods', () => {
  it('finds Monday for any day of the week, including Sunday', () => {
    expect(weekStart('2026-11-02')).toBe('2026-11-02') // Monday
    expect(weekStart('2026-11-05')).toBe('2026-11-02')
    expect(weekStart('2026-11-08')).toBe('2026-11-02') // Sunday belongs to the week that began Monday
    expect(weekStart('2026-11-09')).toBe('2026-11-09')
  })

  it('builds daily and weekly ranges and rejects invalid dates', () => {
    expect(periodFor('daily', '2026-11-04')).toEqual({ from: '2026-11-04', to: '2026-11-04' })
    expect(periodFor('weekly', '2026-11-04')).toEqual({ from: '2026-11-02', to: '2026-11-08' })
    expect(periodFor('daily', '2026-13-40')).toBeNull()
    expect(periodFor('weekly', '')).toBeNull()
  })

  it('moves by a day or a week, across month boundaries', () => {
    expect(shiftAnchor('daily', '2026-11-01', -1)).toBe('2026-10-31')
    expect(shiftAnchor('weekly', '2026-11-02', 1)).toBe('2026-11-09')
  })
})

describe('operational summary', () => {
  it('matches the dashboard for the same period', () => {
    const s = buildSummary(input, 'weekly', '2026-11-04', meta)!
    const d = buildDashboard(input, { from: '2026-11-02', to: '2026-11-08' })
    expect(s.kpis).toEqual(d.kpis)
    expect(s.lines).toEqual(d.lines)
    expect(s.daily).toEqual(d.daily)
    expect(s.approvedReportCount).toBe(d.approvedReportCount)
  })

  it('marks a period that has not ended as in progress', () => {
    expect(buildSummary(input, 'daily', '2026-11-07', meta)!.inProgress).toBe(true)
    expect(buildSummary(input, 'daily', '2026-11-06', meta)!.inProgress).toBe(false)
    expect(buildSummary(input, 'weekly', '2026-11-04', meta)!.inProgress).toBe(true)
  })

  it('lists reports that are not counted, by state', () => {
    const s = buildSummary(input, 'daily', '2026-11-07', meta)!
    const day = REPORTS.filter((r) => r.reportDate === '2026-11-07')
    expect(s.excluded.draft).toBe(day.filter((r) => r.status === 'draft').length)
    expect(s.excluded.returned).toBe(day.filter((r) => r.status === 'returned').length)
    expect(s.excluded.awaitingReview).toBe(day.filter((r) => r.status === 'pending_review' || r.status === 'revised').length)
    expect(s.excluded.draft + s.excluded.returned).toBeGreaterThan(0)
  })

  it('returns null for an invalid anchor and has null rates for a period with no production', () => {
    expect(buildSummary(input, 'daily', 'nope', meta)).toBeNull()
    const sunday = buildSummary(input, 'daily', '2026-11-01', meta)!
    expect(sunday.approvedReportCount).toBe(0)
    expect(sunday.kpis.rejectionRate).toBeNull()
  })
})

describe('summary CSV', () => {
  it('carries metadata, totals and named sections with a dated filename', () => {
    const s = buildSummary(input, 'weekly', '2026-11-04', meta)!
    const { filename, csv } = buildSummaryCsv(s)
    expect(filename).toBe('shopfloor-weekly-summary-2026-11-02_to_2026-11-08.csv')
    expect(csv).toContain('Generated by,Mira Santos')
    expect(csv).toContain('Period status,In progress (not complete)')
    expect(csv).toContain(`Produced quantity,${s.kpis.producedQuantity}`)
    expect(csv).toContain('Production line,')
    expect(csv).toContain('Downtime category,')
    expect(buildSummaryCsv(buildSummary(input, 'daily', '2026-11-06', meta)!).filename).toBe('shopfloor-daily-summary-2026-11-06.csv')
  })
})
